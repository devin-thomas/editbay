import assert from "node:assert/strict";
import { chromium } from "playwright";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
const base = new URL(process.argv[2] || "http://127.0.0.1:8793");
if (!["http:", "https:"].includes(base.protocol) || base.username || base.password) throw new Error("Expected a plain HTTP(S) preview URL");
const endpoint = "https://editbay.uppercut-labs.com/mcp";
// Copy removed by the dvn restyle; any return is a regression.
const removed = ["Keep the proof", "A visible trail", "Inspect the work", "NEUTRAL STUDY", "EDITING ROOM", "Built for intentional edits", "Guidance in the cloud"];
const output = await mkdtemp(join(tmpdir(), "editbay-browser-"));
const browser = await chromium.launch();
try {
  for (const width of [1440, 1024, 768, 390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
    await page.goto(base.href, { waitUntil: "networkidle" });
    assert.equal(await page.locator("h1").count(), 1);
    assert.ok(await page.locator("#connect").isVisible());
    assert.ok(await page.locator("#copy-prompt").isVisible());
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `horizontal overflow at ${width}`);
    const logos = await page.locator(".agents img").evaluateAll((images) => images.map((image) => ({ src: image.getAttribute("src"), natural: image.naturalWidth, rendered: image.getBoundingClientRect().width })));
    assert.equal(logos.length, 3);
    for (const logo of logos) assert.ok(logo.natural > 0 && logo.rendered >= 18, `agent artwork failed to render: ${logo.src}`);
    const text = await page.locator("body").innerText();
    for (const phrase of removed) assert.ok(!text.toUpperCase().includes(phrase.toUpperCase()), `removed copy returned: ${phrase}`);
    await page.screenshot({ path: join(output, `${width}.png`), fullPage: true });
    assert.deepEqual(errors, []);
    await context.close();
  }
  const context = await browser.newContext({ reducedMotion: "reduce" });
  const page = await context.newPage();
  await page.goto(base.href);
  let prompt = (await page.locator("#setup-prompt").innerText()).trim();
  assert.ok(prompt.includes("claude plugin marketplace add devin-thomas/editbay") && prompt.includes("claude plugin install editbay@editbay") && prompt.includes("video-director"));
  assert.equal(await page.locator("#pick-claude").getAttribute("aria-pressed"), "true");
  await page.locator("#pick-mcp").click();
  assert.equal(await page.locator("#pick-claude").getAttribute("aria-pressed"), "false");
  prompt = (await page.locator("#setup-prompt").innerText()).trim();
  assert.ok(prompt.includes(endpoint) && prompt.includes("video-director") && prompt.includes("get_tool"));
  const deny = () => page.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async () => { throw new Error("denied"); } } }));
  const expect = (wanted) => page.evaluate((value) => Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async (text) => { if (text !== value) throw new Error("wrong text"); } } }), wanted);
  await deny();
  await page.locator("#copy-prompt").click();
  await page.locator("#prompt-status").filter({ hasText: "Clipboard unavailable" }).waitFor();
  assert.equal((await page.evaluate(() => getSelection().toString())).trim(), prompt);
  await expect(prompt);
  await page.locator("#copy-prompt").click();
  await page.locator("#prompt-status").filter({ hasText: "Prompt copied" }).waitFor();
  await deny();
  await page.locator("#copy-endpoint").click();
  await page.locator("#copy-status").filter({ hasText: "Clipboard unavailable" }).waitFor();
  assert.equal(await page.evaluate(() => getSelection().toString()), endpoint);
  await expect(endpoint);
  await page.locator("#copy-endpoint").click();
  await page.locator("#copy-status").filter({ hasText: "URL copied" }).waitFor();
  await context.close();
  console.log(`PASS: five viewports, agent artwork, removed copy, prompt and URL copy with clipboard denial and success. Screenshots: ${output}`);
} finally { await browser.close(); }
